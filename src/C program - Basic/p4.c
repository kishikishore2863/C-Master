#include <stdio.h>
// C program to ADD two Integers
int main() {
    int a,b,sum=0;
    printf("enter a first number:");
    scanf("%d",&a);
    printf("enter a second number:");
    scanf("%d",&b);
    sum =a+b;
    printf("the sum of %d and %d is %d",a,b,sum);
    return 0;
}